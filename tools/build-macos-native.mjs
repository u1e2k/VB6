/** Reproducible independent browser/Node compiler package and native SDK payload. */
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {bundle} from './bundle.mjs';
// Native source is data inside the browser bundle. CRLF checkouts must not
// change the SDK revision, generated JavaScript, or source build-kit bytes.
export function readMacOSSDK(root) {
  const dir=path.join(root,'packages/macos-native'),files={};
  const sourceText=file=>fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');
  for(const name of fs.readdirSync(path.join(dir,'native')).sort()) {
    if(!/^[a-z0-9-]+\.(cpp|mm|hpp)$/.test(name))continue;
    files['native/'+name]=sourceText(path.join(dir,'native',name));
  }
  for(const [out,input]of Object.entries({'build.mjs':'build-driver.mjs','target.js':'target.js','mach-o.js':'mach-o.js'}))files[out]=sourceText(path.join(dir,'src',input));
  files.LICENSE=sourceText(path.join(root,'LICENSE'));
  return files;
}
export function buildMacOSPackage(root=path.resolve(import.meta.dirname,'..')) {
  const dir=path.join(root,'packages/macos-native'),files=readMacOSSDK(root);
  const revision=createHash('sha256').update(JSON.stringify(files)).digest('hex');
  fs.writeFileSync(path.join(dir,'src/sdk-payload.js'),'// Generated by tools/build-macos-native.mjs.\nexport const SDK_REVISION='+JSON.stringify(revision)+';\nexport const SDK_FILES='+JSON.stringify(files)+';\n');
  const globalName='VB6MacOS',iife=bundle(path.join(dir,'src/index.js'),globalName);
  const names=['compileMacOS','cppText','createMacOSBuildKit','MACOS_TARGET','MacOSCompileError','macOSOptions','macOSInfoPlist','MACOS_CONTROLS','MACOS_API_SIGNATURES','resolveMacOSDeclaration','macOSControlReport','inspectMachO','importFiles','MacOSCompilerClient','verifyMacOSAppArchive','sha256Bytes','MACOS_PROTOCOL','MACOS_LIMITS','macOSBridgeURL','normalizeMacOSBuildRequest'];
  const esm=iife.replace("(()=>{'use strict';", "const __api=(()=>{'use strict';").replace(/globalThis\["VB6MacOS"\]=(__modules\[\d+\]);/, 'return $1;')+'\n'+names.map(n=>`export const ${n}=__api.${n};`).join('\n')+'\n';
  fs.mkdirSync(path.join(dir,'dist'),{recursive:true});fs.mkdirSync(path.join(root,'dist'),{recursive:true});
  fs.writeFileSync(path.join(dir,'dist/index.js'),esm);fs.writeFileSync(path.join(dir,'dist/browser.js'),iife);fs.writeFileSync(path.join(root,'dist/vb6-macos.js'),iife);
  fs.writeFileSync(path.join(dir,'LICENSE'),files.LICENSE);
  return {revision,sourceFiles:Object.keys(files).length,compilerBytes:Buffer.byteLength(esm)};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(buildMacOSPackage()));
