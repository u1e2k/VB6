/** Compile and execute only checked-in regression fixtures, never user projects. */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {valueRuntime} from '../packages/vbnet-migration/src/runtime-values.js';
import {arrayRuntime} from '../packages/vbnet-migration/src/runtime-arrays.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = path.join(root, 'artifacts/vbnet-migration/runtime');
await fs.mkdir(directory, {recursive: true});
await fs.writeFile(path.join(directory, 'Runtime.vbproj'), '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Exe</OutputType><RootNamespace></RootNamespace><OptionStrict>On</OptionStrict><MyType>Empty</MyType><Deterministic>true</Deterministic><EnableDefaultCompileItems>false</EnableDefaultCompileItems></PropertyGroup><ItemGroup><Compile Include="Values.vb"/><Compile Include="Arrays.vb"/><Compile Include="Main.vb"/></ItemGroup></Project>\n');
await fs.writeFile(path.join(directory, 'Values.vb'), valueRuntime);
await fs.writeFile(path.join(directory, 'Arrays.vb'), arrayRuntime);
await fs.copyFile(path.join(root, 'tests/fixtures/vbnet-migration/runtime-main.vb'), path.join(directory, 'Main.vb'));
const result = spawnSync('dotnet', ['run', '--project', 'Runtime.vbproj', '--configuration', 'Release'], {cwd:directory, encoding:'utf8', timeout:180_000, maxBuffer:8*1024*1024, env:{...process.env,DOTNET_CLI_TELEMETRY_OPTOUT:'1',DOTNET_NOLOGO:'1'}});
const output=(result.stdout||'')+(result.stderr||'');
await fs.writeFile(path.join(directory,'execution.log'), output+(result.error?'\n'+result.error.message:''));
process.stdout.write(output);
if (result.error) throw result.error;
if (result.status !== 0 || !/VB6_MIGRATION_RUNTIME_OK \d+/.test(output)) throw new Error('Generated runtime compilation/execution failed; see artifacts/vbnet-migration/runtime/execution.log');
